export function LanguageProvider({ children }) {
    const [language, setLanguageState] = useState(() => {
        const saved = localStorage.getItem('bharatverse_language');
        return SUPPORTED_LANGUAGES.some((l) => l.code === saved) ? saved : 'en';
    });
    const setLanguage = (lang) => {
        setLanguageState(lang);
        localStorage.setItem('bharatverse_language', lang);
    };
    const t = (key) => {
        return UI_TRANSLATIONS[key]?.[language] || UI_TRANSLATIONS[key]?.['en'] || key;
    };
    const langInfo = SUPPORTED_LANGUAGES.find((l) => l.code === language) || SUPPORTED_LANGUAGES[0];
    return (_jsx(LanguageContext.Provider, { value: { language, setLanguage, t, langInfo }, children: children }));
}
export const useLanguage = () => useContext(LanguageContext);
